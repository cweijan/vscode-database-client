#!/usr/bin/env node
/**
 * Copies the shipped 9.0.2 webview stylesheets into the recovered source tree so the candidate
 * build renders with the target's own CSS instead of hand-written replacements.
 *
 * Vue's scoped-style attribute (`data-v-<hash>`) is derived from the build's file layout, so the
 * recovered components cannot carry the target's hash. The attribute is therefore dropped from the
 * selectors, which keeps every declaration but makes the rules apply by class name — the same
 * visual result, without needing to fake scope ids per component.
 *
 * Fonts and other url() assets are copied next to the stylesheet and the references rewritten.
 *
 * Usage: node scripts/source-recovery/sync-webview-styles.mjs --target-root <installed-extension>
 */
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HASH_SUFFIX = /-([A-Za-z0-9_-]{8,12})$/;
const SCOPE_ATTRIBUTE = /\[data-v-[0-9a-f]+\]/g;
const ASSET_URL = /url\(\s*(?:"|')?\.\/([^"')]+)(?:"|')?\s*\)/g;
const ASSET_FILE = /\.(?:woff2?|ttf|eot|wasm|png|jpe?g|gif|svg)$/i;

function parseArguments(argv) {
  const options = { targetRoot: null, output: "src/modern-webview/styles/target" };
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--target-root") options.targetRoot = argv[++index];
    else if (argument === "--output") options.output = argv[++index];
    else if (argument === "--help" || argument === "-h") {
      console.log(
        [
          "Usage:",
          "  node scripts/source-recovery/sync-webview-styles.mjs --target-root <installed-extension>",
          "",
          "Options:",
          "  --target-root <path> Installed extension directory.",
          "  --output <dir>       Destination inside the repository (default: src/modern-webview/styles/target).",
        ].join("\n"),
      );
      process.exit(0);
    } else {
      throw new Error(`Unknown argument: ${argument}`);
    }
  }
  if (!options.targetRoot) throw new Error("--target-root is required");
  return options;
}

function stableName(fileName, used) {
  const base = path.basename(fileName, path.extname(fileName)).replace(HASH_SUFFIX, "");
  const candidate = `${base || "chunk"}.css`;
  const collisions = used.get(candidate) ?? 0;
  used.set(candidate, collisions + 1);
  return collisions === 0 ? candidate : `${base}-${collisions + 1}.css`;
}

async function main() {
  const options = parseArguments(process.argv.slice(2));
  const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
  const assetsDirectory = path.join(options.targetRoot, "out", "webview", "assets");
  const outputDirectory = path.resolve(repositoryRoot, options.output);

  await fs.rm(outputDirectory, { recursive: true, force: true });
  await fs.mkdir(path.join(outputDirectory, "assets"), { recursive: true });

  const entries = (await fs.readdir(assetsDirectory, { withFileTypes: true }))
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
    .sort();

  const used = new Map();
  const written = [];

  for (const file of entries.filter((name) => name.endsWith(".css"))) {
    const source = await fs.readFile(path.join(assetsDirectory, file), "utf8");
    const rewritten = [];
    let match;
    while ((match = ASSET_URL.exec(source)) !== null) {
      rewritten.push(match[1].replace(/\?.*$/, ""));
    }
    ASSET_URL.lastIndex = 0;

    for (const asset of new Set(rewritten)) {
      if (!ASSET_FILE.test(asset)) continue;
      const target = path.join(outputDirectory, "assets", asset);
      await fs.copyFile(path.join(assetsDirectory, asset), target);
    }

    const css = source
      .replace(SCOPE_ATTRIBUTE, "")
      .replace(ASSET_URL, (_match, asset) => `url(./assets/${asset.replace(/\?.*$/, "")})`);

    const target = stableName(file, used);
    await fs.writeFile(path.join(outputDirectory, target), css, "utf8");
    written.push(target);
  }

  const index = [
    "// Generated by scripts/source-recovery/sync-webview-styles.mjs — do not edit.",
    ...written.map((file) => `import "./${file}";`),
    "",
  ].join("\n");
  await fs.writeFile(path.join(outputDirectory, "index.ts"), index, "utf8");

  console.log(`synced ${written.length} target stylesheets into ${options.output}`);
}

await main();
